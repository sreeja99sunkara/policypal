"""Build dist/hf-space/: a clean directory to push to a Hugging Face Docker Space.

    python scripts/make_space_bundle.py [--out dist/hf-space]

Copies an allow-list of files (never .env, eval/, tests/, notebooks/, venv/,
.git/ or other PDFs) and writes the Space-specific files:

- README.md with the Hugging Face YAML front matter;
- Dockerfile: base + wheel builders + `demo` (last stage), with
  PRELOAD_MODELS defaulting to true, because Hugging Face builds the root
  Dockerfile with no build arguments and the Space's disk is ephemeral;
- requirements.txt re-encoded from UTF-16 to UTF-8 (the Hub treats UTF-16
  text as binary);
- .gitattributes: LF for *.sh, Git LFS for the PDF.

Secrets are never read or written: GROQ_API_KEY is set as a Space secret.
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
POLICY_PDF = "data/raw/StarHealthAssureInsurancePolicy-Policy-wording.pdf"
GITHUB_URL = "https://github.com/<your-github-user>/policypal"  # placeholder

# (source, destination) relative to ROOT / the bundle. Directories are copied
# recursively, skipping caches.
ALLOW = [
    ("app", "app"),
    ("streamlit_app.py", "streamlit_app.py"),
    ("docker/start-demo.sh", "docker/start-demo.sh"),
    ("docker/requirements-api.txt", "docker/requirements-api.txt"),
    ("docker/requirements-ui.txt", "docker/requirements-ui.txt"),
    (POLICY_PDF, POLICY_PDF),
]
# Never allowed in the bundle, whatever the allow-list says.
FORBIDDEN_PARTS = {".env", "eval", "tests", "notebooks", "venv", ".git", "__pycache__"}
SKIP_NAMES = {"__pycache__", ".pytest_cache", ".ipynb_checkpoints"}
SKIP_SUFFIXES = {".pyc", ".pyo"}

FRONT_MATTER = """---
title: PolicyPal
emoji: 🏥
colorFrom: blue
colorTo: green
sdk: docker
app_port: 7860
pinned: false
short_description: Q&A over a health insurance policy, with page citations
---
"""

SPACE_README = FRONT_MATTER + f"""
# PolicyPal

PolicyPal answers questions about a health insurance policy and cites the
pages it used. It is a retrieval-augmented generation (RAG) app: the policy
PDF is split into text and table chunks, retrieved with hybrid search
(embeddings + BM25) and a cross-encoder reranker, and answered by an LLM
(served by Groq) that is told to use only the retrieved text.

**This Space is a demo on one fixed policy**: the Star Health Assure
Insurance Policy wording. Uploading your own PDF is disabled here. To keep the
demo affordable it has limits: per-visitor rate limits (10 questions a minute,
100 a day), a daily cap on questions across all visitors, one question
answered at a time (others wait briefly), and a 500-character question limit.
When a limit is reached the app says so and when to try again.

Answers are generated by an LLM from extracts of the policy and can be wrong
or incomplete. Check the cited pages; this is not insurance advice.

Source code, setup and evaluation: {GITHUB_URL}

## Known limitations

- **"What are the sum insured options available?"** is not answered fully:
  the table header that lists all nine options ranks too low to be retrieved
  (the word "options" does not appear in the policy).
- **"What is the ICU charge limit?"** is refused: the Schedule of Benefits row
  ("ICU/Operation Theatre Charges: Actual") is retrieved but the reranker
  scores it below the cut-off.
- **"What is the waiting period for cataract surgery?"** is refused: the
  24-month waiting-period clause and the list that names cataract are in
  different chunks, and only the list is retrieved.
- The co-payment answer can omit its condition (10% applies only to people
  aged 61 or above at entry).
- Some tables have no title, so their chunks read "Untitled table".
- Each question is answered on its own (no conversation memory). Answers take
  roughly 10–20 s on this CPU-only Space.
- After a period of inactivity the Space sleeps; the first visit then waits
  for it to start (models load and the policy is indexed, about 2 minutes).
"""

GITATTRIBUTES = """# Shell scripts run in the Linux container: keep LF.
*.sh text eol=lf
# The Hub stores binary files with LFS/Xet.
*.pdf filter=lfs diff=lfs merge=lfs -text
"""

DOCKERIGNORE = """.git
.gitattributes
README.md
"""


def space_dockerfile(src: str) -> str:
    """Root Dockerfile -> Space Dockerfile: keep base, the wheel builders and
    demo (in that order, demo last); PRELOAD_MODELS defaults to true."""
    marker = re.compile(r"^# -{20,} (\w+)\s*$", re.M)
    starts = [(m.start(), m.group(1)) for m in marker.finditer(src)]
    names = [n for _, n in starts]
    for needed in ("base", "wheels", "demo"):
        if needed not in names:
            sys.exit(f"Dockerfile: section '{needed}' not found (found {names})")
    bounds = {name: (pos, starts[i + 1][0] if i + 1 < len(starts) else len(src))
              for i, (pos, name) in enumerate(starts)}
    head = src[: starts[0][0]]
    # keep the syntax line and ARG PYTHON_VERSION from the head, new comment
    syntax = re.search(r"^# syntax=.*$", head, re.M)
    pyver = re.search(r"^ARG PYTHON_VERSION=.*$", head, re.M)
    if not (syntax and pyver):
        sys.exit("Dockerfile: syntax line or ARG PYTHON_VERSION not found")
    body = "".join(src[slice(*bounds[n])] for n in ("base", "wheels", "demo"))

    demo = src[slice(*bounds["demo"])]
    if demo.count("ARG PRELOAD_MODELS=false") != 1:
        sys.exit("Dockerfile: demo stage has no 'ARG PRELOAD_MODELS=false'")
    body = body.replace(demo, demo.replace(
        "ARG PRELOAD_MODELS=false",
        "# Models baked into the image: the Space's disk is ephemeral, and Hugging\n"
        "# Face passes no build arguments, so this default must be true here.\n"
        "ARG PRELOAD_MODELS=true",
    ))
    out = (
        f"{syntax.group(0)}\n"
        "# PolicyPal demo for a Hugging Face Docker Space. Generated by\n"
        "# scripts/make_space_bundle.py from the repo's Dockerfile; edit that, not this.\n"
        "# One container: uvicorn on 127.0.0.1:8000, Streamlit on $PORT (7860).\n"
        "# Runs as uid 1000. No secrets: GROQ_API_KEY is a Space secret (run time only).\n\n"
        f"{pyver.group(0)}\n\n{body.rstrip()}\n"
    )
    # Hugging Face builds the last stage; it must be demo.
    last_from = re.findall(r"^FROM .* AS (\w[\w-]*)\s*$", out, re.M)[-1]
    assert last_from == "demo", last_from
    assert "USER app" in demo and "useradd --create-home --uid 1000 app" in out
    return out


def copy_item(src: Path, dst: Path) -> None:
    if src.is_dir():
        for p in sorted(src.rglob("*")):
            rel = p.relative_to(src)
            if any(part in SKIP_NAMES for part in rel.parts) or p.suffix in SKIP_SUFFIXES:
                continue
            if p.is_file():
                target = dst / rel
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(p, target)
    else:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.replace("\r\n", "\n").encode("utf-8"))


def check_bundle(out: Path) -> list[Path]:
    files = sorted(p for p in out.rglob("*") if p.is_file())
    problems = []
    for p in files:
        rel = p.relative_to(out)
        if FORBIDDEN_PARTS & set(rel.parts) or rel.name.startswith(".env"):
            problems.append(f"forbidden path: {rel}")
        if p.suffix.lower() == ".pdf" and rel.as_posix() != POLICY_PDF:
            problems.append(f"unexpected PDF: {rel}")
        data = p.read_bytes()
        if re.search(rb"gsk_[A-Za-z0-9]{10,}", data):
            problems.append(f"Groq-key-like string in {rel}")
    sh = (out / "docker/start-demo.sh").read_bytes()
    if b"\r" in sh or not sh.startswith(b"#!/usr/bin/env bash\n"):
        problems.append("docker/start-demo.sh is not LF-only")
    if problems:
        sys.exit("Bundle check failed:\n  " + "\n  ".join(problems))
    return files


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default="dist/hf-space", help="output directory (replaced)")
    out = (ROOT / ap.parse_args().out).resolve()
    if ROOT / "dist" not in out.parents:
        sys.exit(f"refusing to write outside {ROOT / 'dist'}: {out}")
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    for src, dst in ALLOW:
        copy_item(ROOT / src, out / dst)

    # UTF-16 freeze -> UTF-8 (pip reads both; the Hub would treat UTF-16 as binary)
    raw = (ROOT / "requirements.txt").read_bytes()
    text = raw.decode("utf-16") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8-sig")
    write_text(out / "requirements.txt", text)

    write_text(out / "Dockerfile", space_dockerfile((ROOT / "Dockerfile").read_text(encoding="utf-8")))
    write_text(out / "README.md", SPACE_README)
    write_text(out / ".gitattributes", GITATTRIBUTES)
    write_text(out / ".dockerignore", DOCKERIGNORE)
    # start-demo.sh: force LF bytes regardless of the checkout's line endings
    sh = out / "docker/start-demo.sh"
    sh.write_bytes(sh.read_bytes().replace(b"\r\n", b"\n"))

    files = check_bundle(out)
    total = sum(p.stat().st_size for p in files)
    for p in files:
        print(f"{p.stat().st_size:>10,}  {p.relative_to(out).as_posix()}")
    print(f"{len(files)} files, {total / 1e6:.2f} MB -> {out}")


if __name__ == "__main__":
    main()
